"""Generates the status bar day icons: one vector drawable per day 1 to 32, in Latin and Devanagari
digits, from Noto Sans Devanagari Bold (SIL Open Font License 1.1).

Android 16 replaces a bitmap notification small icon with the app icon, so the status bar day has
to come from a drawable resource. Run from the repository root:

    python android/tools/generate_day_icons.py path/to/NotoSansDevanagari-Variable.ttf
"""

import pathlib
import sys

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

OUT = pathlib.Path("android/app/src/main/res/drawable")
VIEWPORT = 24.0
PADDING = 1.0
# Two digits are drawn a little condensed so they stay tall enough to read at status bar size.
TWO_DIGIT_SQUEEZE = 0.86
SCRIPTS = {"en": "0123456789", "ne": "०१२३४५६७८९"}

TEMPLATE = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by android/tools/generate_day_icons.py from Noto Sans Devanagari Bold (OFL 1.1). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
    <path
        android:fillColor="@android:color/white"
        android:pathData="{path}" />
</vector>
"""


def main(font_path: str) -> None:
    font = instantiateVariableFont(TTFont(font_path), {"wght": 700})
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    units = font["head"].unitsPerEm
    ascent = font["OS/2"].sCapHeight or units * 0.7
    for script, digits in SCRIPTS.items():
        for day in range(1, 33):
            text = "".join(digits[int(c)] for c in str(day))
            names = [cmap[ord(c)] for c in text]
            width = sum(glyphs[n].width for n in names)
            squeeze = TWO_DIGIT_SQUEEZE if len(text) > 1 else 1.0
            box = VIEWPORT - 2 * PADDING
            scale = min(box / (width * squeeze), box / (ascent * 1.25))
            drawn_width = width * squeeze * scale
            x0 = (VIEWPORT - drawn_width) / 2
            baseline = VIEWPORT / 2 + ascent * scale / 2
            pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
            x = 0.0
            for name in names:
                transform = (scale * squeeze, 0, 0, -scale, x0 + x * scale * squeeze, baseline)
                glyphs[name].draw(TransformPen(pen, transform))
                x += glyphs[name].width
            path = pen.getCommands()
            (OUT / f"ic_day_{script}_{day}.xml").write_text(TEMPLATE.format(path=path), encoding="utf-8")


if __name__ == "__main__":
    main(sys.argv[1])
